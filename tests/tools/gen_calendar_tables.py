#!/usr/bin/env python3
"""Generate the calendar phase tables for the host tests from plantOS.yaml.

Runs the same validation and C++ rendering as the firmware build
(components/calendar_manager/phase_tables.py), so the tests see exactly the tables
that end up in main.cpp.

Usage: gen_calendar_tables.py <plantOS.yaml> <out.h>
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(HERE, "..", "..", "components", "calendar_manager"))

from calendar_yaml import load_calendar_block  # noqa: E402
from phase_tables import CalendarError, render_cpp, validate_calendars  # noqa: E402


def main():
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    block = load_calendar_block(sys.argv[1])
    try:
        calendars = validate_calendars(block.get("calendars"))
    except CalendarError as err:
        raise SystemExit(f"plantOS.yaml calendar_manager: {err}")
    text = ("// Generated by tests/tools/gen_calendar_tables.py from plantOS.yaml. Do not edit.\n"
            "#pragma once\n"
            '#include "esphome/components/calendar_manager/phase_table.h"\n\n' + render_cpp(calendars))
    with open(sys.argv[2], "w", encoding="utf-8") as f:
        f.write(text)


if __name__ == "__main__":
    main()
